/**
 * 正文里认识的字段标签（**只认这几个**；别的行按普通段落渲染，不瞎猜）。
 * 与 `decisionEntryTemplate()` 产出的 `**决策**：` 一族对应。
 */
export const BODY_LABELS = ["决策", "依据", "理由", "影响", "结论", "备注", "风险", "边界", "落点"];

/**
 * 一行是不是「标签：内容」——**匹配要宽**，因为写日志的是模型，写法会飘。
 *
 * 实测（用户报的 bug：「最新的这条 影响 为什么不显示标签」）：当时那条写成了
 * `**影响**（DEF-002）：…`，而旧正则要求标签后面**紧跟冒号**，于是这一行没被认出，
 * 退化成普通段落 —— 标签就没了。所以这里容忍：
 *   · 前导项目符号：`- 影响：…` / `* **影响**：…`
 *   · 标签本身加粗/下划线：`**影响**：` / `__影响__：`
 *   · 标签与冒号之间夹注释：`**影响**（DEF-002）：` / `影响 [DEF-002]：`
 *   · 全角 / 半角冒号
 *
 * ★ 仍然**只认白名单里的标签**：`副作用：…` 这类不认（宁可当普通段落，也不瞎猜成标签）。
 */
export function labelLineOf(line: unknown): { label: string; text: string } | null {
	const re = new RegExp(
		"^\\s*(?:[-*·•]\\s*)?" +
		"(?:\\*\\*|__)?\\s*" +
		"(" + BODY_LABELS.join("|") + ")" +
		"\\s*(?:\\*\\*|__)?" +
		"\\s*(?:[（(\\[][^）)\\]]{0,24}[）)\\]]\\s*)?" +
		"[:：]\\s*(.*)$"
	);
	/**
	 * ★ 两段式（2026-10-09 加固）：用户实测仍有个别行没被认出，而磁盘原文按上面的规则**是能认的**
	 *   ⇒ 怀疑行里混了**看不见的字符**（零宽空格、BOM、不换行空格… 界面上完全看不出来）。
	 *   所以先**归一化**再匹配；仍不中就走**兜底**（行首白名单标签 + 30 字内有冒号 ⇒ 认）。
	 */
	const s = String(line === null || line === undefined ? "" : line)
		.replace(/[\u200b-\u200f\u2028\u2029\ufeff\u00a0]/g, " ");
	const m = re.exec(s);
	if (m !== null) return { label: m[1], text: m[2] };

	/**
	 * 兜底：只吃「标签 + 至多 30 字 + 冒号」，不会把普通段落误伤成标签行。
	 * 正常写法在第 ① 步就返回了，走到这儿的都是"还夹着别的字符"的形态。
	 */
	const head = new RegExp("^\\s*(?:[-*·•]\\s*)?(?:\\*\\*|__)?\\s*(" + BODY_LABELS.join("|") + ")");
	const h = head.exec(s);
	if (h === null) return null;
	const rest = s.slice(h[0].length);
	const colon = rest.search(/[:：]/);
	if (colon < 0 || colon > 30) return null;
	return { label: h[1], text: rest.slice(colon + 1).replace(/^\s+/, "").replace(/^(\*\*|__)/, "") };
}
